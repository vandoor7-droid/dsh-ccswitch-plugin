/**
 * cc-switch's Tailwind stylesheet, rebuilt with **every utility prefixed**.
 *
 * ## Why
 *
 * cc-switch styles itself entirely with Tailwind utility classes
 * (`className="flex gap-2"`). DSH's own style rules are ui-primitives + CSS
 * Modules and forbid Tailwind, and an unprefixed build would ship
 * `.flex { display: flex }` into DSH's document where it would apply to any
 * element DSH happens to put in that class. So both halves are renamed:
 * the class in the markup and the rule in the stylesheet gain `dsh-ccs-`.
 *
 * The vendored sources under `src/ccswitch/` stay byte-for-byte upstream — the
 * rename happens here, at build time (an esbuild `onLoad` hook calls
 * {@link prefixSource}). That keeps decision #7 ("reuse the original code
 * unless the stack forces a rewrite") true in git, not just in spirit.
 *
 * ## How the two halves stay in step
 *
 * Tailwind only accepts a class once the prefix is already on it, so we cannot
 * ask it which classes exist while the sources are still unprefixed — and
 * without that list we would not know *which* tokens to prefix (a string like
 * `"Click to block"` must not become `"Click to dsh-ccs-block"`).
 *
 * Two passes over the same config settle it:
 *
 * 1. **Candidates.** Tailwind runs over the raw sources with `@tailwind
 *    utilities;` only and no prefix. Every class selector in the result is
 *    recorded — that set *is* "what the sources actually use as utilities",
 *    by construction.
 * 2. **Emit.** The sources are rewritten with that set, and Tailwind runs
 *    again with `prefix` and the rewritten sources as content. The stylesheet
 *    therefore contains exactly the classes step 1 recognised, and only those.
 *
 * A token the sources use but Tailwind never emitted gets neither a rename nor
 * a rule — it was unstyled before and still is, so nothing silently changes.
 *
 * ## Known limits
 *
 * - A *string* is rewritten when every token is a known utility, or when it
 *   mixes known utilities with tokens carrying a structural character
 *   (`-`, `:`, `[`, `/`). Prose that happens to contain the bare word
 *   `"block"` is left alone; a sentence that also contains `"bg-red-500"`
 *   would not be. Rewriting a non-class string is cosmetic — the renamed text
 *   simply does not match any rule.
 * - `*.test.*` is never rewritten, so cc-switch's own specs keep upstream's
 *   text. They are vitest specs and are not part of `npm test`; wiring that
 *   runner (and its jsdom setup) is a separate step.
 * - `tailwind-merge` validates class names against its own knowledge, so the
 *   copy it is handed has to carry the prefix too — that is handled by
 *   `src/client/tauri-shim/tailwind-merge.mjs`, aliased over the package.
 */
import { readdir, readFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import { transform as esbuildTransform } from 'esbuild'
import postcss from 'postcss'
import tailwindcss from 'tailwindcss'
import autoprefixer from 'autoprefixer'

const require = createRequire(import.meta.url)
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** The one place the prefix is spelled. Everything else derives from it. */
export const PREFIX = 'dsh-ccs-'

/**
 * The class the plugin's own subtree carries, and the selector cc-switch's
 * element-level rules are wrapped in.
 *
 * Chosen so it cannot collide with a Tailwind utility: there is no `root`
 * utility, so `dsh-ccs-root` is never generated by Tailwind itself.
 */
export const ROOT_CLASS = 'dsh-ccs-root'

/** Vendored upstream sources, as copied from cc-switch's `src/`. */
export const SOURCE_DIR = resolve(ROOT, 'src/ccswitch')

const SOURCE_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.jsx', '.html', '.css'])
const REWRITABLE_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.jsx'])
/** cc-switch's own specs: rewritten or not, they must keep upstream's text. */
const SPEC_PATTERN = /\.test\.(ts|tsx|js|jsx)$/

/** Character classes a Tailwind utility carries and English prose does not. */
function hasStructure(token) {
  return token.includes('-') || token.includes(':') || token.includes('[') || token.includes('/')
}

let cachedFiles
let cachedCandidates
let cachedCss

/** Every text file under `src/ccswitch/`, read once. */
async function readFiles(dir = SOURCE_DIR, out = []) {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) {
      await readFiles(path, out)
      continue
    }
    const dot = entry.name.lastIndexOf('.')
    if (dot < 0 || !SOURCE_EXTENSIONS.has(entry.name.slice(dot))) continue
    out.push({ path, text: await readFile(path, 'utf8') })
  }
  return out
}

/** cc-switch's own Tailwind config, with `content` replaced by ours. */
function loadConfig({ prefix, content }) {
  const config = require(resolve(ROOT, 'tailwind.config.cjs'))
  return {
    ...config,
    ...(prefix === undefined ? {} : { prefix }),
    content,
    // `./src/index.html` in the upstream config is the Tauri shell; DSH mounts
    // this plugin into its own document, so only the vendored sources matter.
    corePlugins: { ...config.corePlugins, preflight: false },
  }
}

/**
 * A Tailwind build with a given config and input CSS.
 *
 * `from` has to be a real path inside the repo: postcss resolves `content`
 * globs relative to it, and a bare `undefined` makes Tailwind report "no
 * utility classes were detected" even when there are some.
 */
async function runTailwind(config, css) {
  const result = await postcss([
    tailwindcss(config),
    // Upstream's `postcss.config.cjs` runs autoprefixer too; keeping it means
    // the copied markup needs no browser-specific fixes of its own.
    autoprefixer({ overrideBrowserslist: ['last 4 versions'] }),
  ]).process(css, { from: resolve(ROOT, 'scripts/ccswitch.css.in'), to: undefined })
  return result.css
}

/** Every class selector in a stylesheet, unescaped and de-duplicated. */
function classSelectors(css) {
  const root = postcss.parse(css)
  const classes = new Set()
  root.walkRules((rule) => {
    for (const part of rule.selectors ?? [rule.selector]) {
      for (const match of part.matchAll(/\.((?:\\.|[A-Za-z0-9_-])+)/g)) {
        classes.add(match[1].replace(/\\(.)/g, '$1'))
      }
    }
  })
  return classes
}

/**
 * Add the prefix to one class-list token, in the position Tailwind expects.
 *
 * The prefix goes **after** every variant and **before** the utility, with a
 * leading important `!` between them — verified against Tailwind 3.4 rather
 * than guessed:
 *
 * ```
 * flex                    -> dsh-ccs-flex
 * hover:bg-red-500        -> hover:dsh-ccs-bg-red-500
 * !bg-red-500             -> !dsh-ccs-bg-red-500
 * hover:!bg-red-500       -> hover:!dsh-ccs-bg-red-500
 * dark:flex               -> dark:dsh-ccs-flex
 * w-[calc(1px*2)]         -> dsh-ccs-w-[calc(1px*2)]
 * ```
 *
 * Variant separators are found at bracket depth zero, so an arbitrary variant
 * like `[&:hover]:flex` keeps its inner colon.
 *
 * @param candidates - the known-utility set; a token outside it is returned
 *   unchanged, so a non-class string is never renamed.
 * @param force - prefix even when the token is not in `candidates`. Used for
 *   `@apply` arguments, which are utilities by definition and so are never
 *   *extracted* from a source file in the first place.
 * @returns the prefixed token, or the input when it is not a known utility.
 */
export function prefixToken(token, candidates, force = false) {
  if (!force && !candidates.has(token)) return token
  let head = ''
  let body = token
  let depth = 0
  let cut = -1
  for (let i = 0; i < body.length; i += 1) {
    const char = body[i]
    if (char === '[' || char === '(' || char === '{') depth += 1
    else if (char === ']' || char === ')' || char === '}') depth -= 1
    else if (char === ':' && depth === 0) cut = i
  }
  if (cut >= 0) {
    head = body.slice(0, cut + 1)
    body = body.slice(cut + 1)
  }
  const important = body.startsWith('!') ? '!' : ''
  if (important !== '') body = body.slice(1)
  if (body === '') return token
  return `${head}${important}${PREFIX}${body}`
}

/**
 * Whether a string literal is worth rewriting as a class list.
 *
 * All-known → yes. Otherwise only when it mixes known utilities with tokens
 * that carry a structural character, which is what separates `"bg-red-500/10"`
 * from the word `"block"` sitting in a sentence.
 */
function looksLikeClassList(text, candidates) {
  const tokens = text.split(/\s+/).filter((token) => token !== '')
  if (tokens.length === 0) return false
  let known = 0
  let structural = false
  for (const token of tokens) {
    if (candidates.has(token)) known += 1
    else if (hasStructure(token)) structural = true
  }
  if (known === 0) return false
  return known === tokens.length || structural
}

function rewriteLiteral(text, candidates) {
  if (!looksLikeClassList(text, candidates)) return text
  return text
    .split(/(\s+)/)
    .map((part) => (part.trim() === '' ? part : prefixToken(part, candidates)))
    .join('')
}

/** Token kinds after which a `/` opens a regular expression rather than divides. */
const REGEX_PRECEDERS = new Set([
  '(', ',', '=', ':', '[', '!', '&', '|', '?', '{', '}', ';', '+', '-', '*', '%', '<', '>', '~', '^',
])
const REGEX_KEYWORDS = new Set([
  'return', 'typeof', 'instanceof', 'in', 'of', 'new', 'delete', 'void', 'case', 'do', 'else',
  'yield', 'await',
])

/**
 * Whether a `/` at the current point starts a regex, decided from the text
 * already emitted — the standard heuristic, since JS has no way to ask.
 */
function regexStartsHere(emitted) {
  let i = emitted.length - 1
  while (i >= 0 && /\s/.test(emitted[i])) i -= 1
  if (i < 0) return true
  const char = emitted[i]
  // `a++ / b` and `a-- / b` are divisions; the operator is doubled.
  if ((char === '+' || char === '-') && emitted[i - 1] === char) return false
  if (REGEX_PRECEDERS.has(char)) return true
  if (!/[\w$]/.test(char)) return false
  let start = i
  while (start >= 0 && /[\w$]/.test(emitted[start])) start -= 1
  return REGEX_KEYWORDS.has(emitted.slice(start + 1, i + 1))
}

/** Index just past a regex literal starting at `from` (including its flags). */
function endOfRegex(text, from, n) {
  let i = from + 1
  let inClass = false
  while (i < n) {
    const char = text[i]
    if (char === '\\') {
      i += 2
      continue
    }
    if (char === '\n') return from + 1 // never closed: treat it as a division
    if (char === '[') inClass = true
    else if (char === ']') inClass = false
    else if (char === '/' && !inClass) {
      i += 1
      break
    }
    i += 1
  }
  while (i < n && /[a-z]/i.test(text[i])) i += 1
  return i
}

/**
 * Prefix the class strings in one source file.
 *
 * A small lexer rather than a regex, because the interesting strings are
 * template literals: `` `flex ${cond && "mt-2"}` `` has two static chunks and
 * one expression, and only the chunks are class lists. The expression is
 * scanned as code, so a nested template inside it is handled too.
 */
export function prefixSource(text, candidates) {
  let out = ''
  let buffer = ''
  let mode = 'code'
  /**
   * Whether the current template literal has already emitted its opening
   * backtick. It has as soon as a `${ … }` is reached (that branch writes it),
   * and it has not for a plain `` `text` `` — the closing branch needs to know
   * which, or a one-expression template ends up with an extra backtick.
   */
  let tplOpened = false
  /** Stack of `${ … }` frames currently being scanned as code. */
  const frames = []
  let i = 0
  const n = text.length

  while (i < n) {
    const char = text[i]

    if (mode === 'code') {
      if (char === '/' && text[i + 1] === '/') {
        const end = text.indexOf('\n', i)
        const stop = end < 0 ? n : end
        out += text.slice(i, stop)
        i = stop
        continue
      }
      if (char === '/' && text[i + 1] === '*') {
        const end = text.indexOf('*/', i + 2)
        const stop = end < 0 ? n : end + 2
        out += text.slice(i, stop)
        i = stop
        continue
      }
      // A regular expression, not a division. The distinction matters because
      // a pattern like `/['"]/` contains quotes: entering string mode on one
      // of them swallows the rest of the line and every string after it
      // shifts. The usual heuristic decides — `/` starts a regex unless the
      // previous token is a value it could divide.
      if (char === '/' && regexStartsHere(out)) {
        const start = i
        i = endOfRegex(text, i, n)
        out += text.slice(start, i)
        continue
      }
      if (char === '"' || char === "'") {
        mode = char === '"' ? 'dquote' : 'squote'
        buffer = ''
        i += 1
        continue
      }
      if (char === '`') {
        mode = 'template'
        buffer = ''
        tplOpened = false
        i += 1
        continue
      }
      if (char === '}' && frames.length > 0) {
        const frame = frames[frames.length - 1]
        if (frame.depth === 0) {
          frames.pop()
          // The `}` closes the `${ … }` expression, so it belongs to the
          // output as code — not to the template chunk we are about to resume.
          // The template that expression sits in already emitted its opening
          // backtick when the `${` was reached.
          out += char
          mode = 'template'
          tplOpened = true
          i += 1
          continue
        }
        frame.depth -= 1
        out += char
        i += 1
        continue
      }
      if (char === '{' && frames.length > 0) {
        frames[frames.length - 1].depth += 1
      }
      out += char
      i += 1
      continue
    }

    if (mode === 'dquote' || mode === 'squote') {
      const quote = mode === 'dquote' ? '"' : "'"
      if (char === '\\') {
        buffer += char + (text[i + 1] ?? '')
        i += 2
        continue
      }
      if (char === quote) {
        out += quote + rewriteLiteral(buffer, candidates) + quote
        // Cleared, or the content is appended a second time by the flush at
        // the end of the scan.
        buffer = ''
        mode = 'code'
        i += 1
        continue
      }
      if (char === '\n') {
        // Unterminated: emit as-is and get back to code rather than swallow
        // the rest of the file.
        out += quote + buffer
        buffer = ''
        mode = 'code'
        continue
      }
      buffer += char
      i += 1
      continue
    }

    // mode === 'template'
    if (char === '\\') {
      buffer += char + (text[i + 1] ?? '')
      i += 2
      continue
    }
    if (char === '`') {
      out += (tplOpened ? '' : '`') + rewriteLiteral(buffer, candidates) + '`'
      buffer = ''
      tplOpened = false
      mode = 'code'
      i += 1
      continue
    }
    if (char === '$' && text[i + 1] === '{') {
      // Only the first expression in a literal owes an opening backtick; a
      // second one resumes a template that is already open.
      out += (tplOpened ? '' : '`') + rewriteLiteral(buffer, candidates) + '${'
      buffer = ''
      tplOpened = true
      frames.push({ depth: 0 })
      mode = 'code'
      i += 2
      continue
    }
    buffer += char
    i += 1
  }

  if (buffer !== '') out += buffer
  return out
}

/**
 * The set of class names the vendored sources use as Tailwind utilities.
 *
 * Memoised: the whole build (candidate pass, every source rewrite, and the
 * stylesheet) shares one answer, so a token cannot be renamed on one side and
 * not the other.
 */
export async function candidates() {
  if (cachedCandidates) return cachedCandidates
  if (!cachedFiles) cachedFiles = await readFiles()
  const content = cachedFiles.map((file) => ({ raw: file.text }))
  const css = await runTailwind(loadConfig({ prefix: undefined, content }), '@tailwind utilities;')
  const classes = classSelectors(css)
  // `dark` shows up as a selector because of `darkMode: ["selector", ".dark"]`,
  // but it is the *state marker*, not a utility — and cc-switch's own code
  // reads and writes it as an API string (`classList.contains("dark")`,
  // `useDarkMode`). Renaming it there would silently break dark mode, so it is
  // excluded from the rewrite. The plugin's root carries both `dark` and
  // `dsh-ccs-dark` when DSH is dark, which is what satisfies the authored
  // `:root`/`.dark` variable blocks and Tailwind's prefixed `dark:` variants
  // respectively.
  classes.delete('dark')
  cachedCandidates = classes
  return cachedCandidates
}

/** Rewrite every vendored source, memoised on the candidate set. */
export async function prefixedSources() {
  const set = await candidates()
  if (!cachedFiles) cachedFiles = await readFiles()
  return cachedFiles
    .filter((file) => !SPEC_PATTERN.test(file.path))
    .filter((file) => REWRITABLE_EXTENSIONS.has(file.path.slice(file.path.lastIndexOf('.'))))
    .map((file) => ({ path: file.path, text: prefixSource(file.text, set) }))
}

/**
 * Prefix every `@apply` argument in cc-switch's entry stylesheet.
 *
 * With `prefix` set, Tailwind's `@apply` resolves the *prefixed* name —
 * `@apply font-sans` fails with "The `font-sans` class does not exist". The
 * vendored file keeps upstream's text, so the rename happens here on the way
 * in. These arguments are utilities by definition, so they are prefixed
 * unconditionally rather than looked up in the candidate set (the candidate
 * pass only ever sees source files, never this stylesheet).
 */
export function prefixApplyDirectives(css) {
  return css.replace(/(@apply\s+)([^;]+)(;)/g, (_match, head, body, tail) => {
    const tokens = body.split(/\s+/).filter((token) => token !== '')
    return head + tokens.map((token) => prefixToken(token, EMPTY, true)).join(' ') + tail
  })
}

const EMPTY = new Set()

/**
 * Wrap element-level rules in the plugin's root, so they cannot restyle DSH.
 *
 * cc-switch's stylesheet carries a small reset of its own — `* { box-sizing }`,
 * `html { font-family }`, `body { … }`, `::-webkit-scrollbar { … }` — and none
 * of that may reach DSH's document. Rules that name a class are left alone:
 * the prefixed utilities only match this plugin's markup anyway, and the
 * authored component classes (`.glass`, `.ui-checkbox`) are distinctive enough
 * to leave global so portaled menus and dialogs still find them.
 *
 * Two exceptions, both deliberately global:
 *
 * - `:root` / `.dark` hold only custom properties with cc-switch-specific
 *   names (`--bg-app`, `--action-bg` …). DSH defines `--dsw-*`, so there is no
 *   collision, and keeping them global is what lets a Radix portal — which
 *   escapes the wrapper entirely — still resolve them.
 * - Rules inside `@keyframes` are frames, not selectors, and wrapping one
 *   would silently kill the animation.
 */
export function scopeElementRules(css) {
  const root = postcss.parse(css)
  root.walkRules((rule) => {
    if (insideKeyframes(rule)) return
    const selectors = rule.selectors ?? [rule.selector]
    const needsScope = selectors.every((selector) => (
      !selector.includes('.') && !selector.includes(':root')
    ))
    if (!needsScope) return
    rule.selectors = selectors.map((selector) => `.${ROOT_CLASS} ${selector}`.replace(/\s+/g, ' '))
  })
  return root.toString()
}

/** Whether a rule belongs to an `@keyframes` body rather than to the document. */
function insideKeyframes(rule) {
  for (let node = rule.parent; node; node = node.parent) {
    if (node.type === 'atrule' && /^(?:-webkit-)?keyframes$/.test(node.name)) return true
  }
  return false
}

/**
 * The compiled, prefixed stylesheet for cc-switch, minified and ready to inject.
 *
 * Returns `''` when `src/ccswitch/index.css` has not been copied in yet, so a
 * build of the plugin before any upstream component is vendored stays cheap.
 */
export async function buildCss() {
  if (cachedCss !== undefined) return cachedCss
  const entry = resolve(SOURCE_DIR, 'index.css')
  let input
  try {
    input = await readFile(entry, 'utf8')
  } catch {
    cachedCss = ''
    return cachedCss
  }
  const sources = await prefixedSources()
  const content = [
    ...sources.map((file) => ({ raw: file.text })),
    // Files we deliberately do not rewrite (the upstream specs) still tell
    // Tailwind what to emit; they simply cannot contribute a prefixed class.
    ...((cachedFiles ?? []).filter((file) => SPEC_PATTERN.test(file.path)).map((file) => ({ raw: file.text }))),
  ]
  const raw = await runTailwind(
    loadConfig({ prefix: PREFIX, content }),
    prefixApplyDirectives(input),
  )
  const scoped = scopeElementRules(raw)
  const minified = await esbuildTransform(scoped, { loader: 'css', minify: true })
  cachedCss = minified.code
  return cachedCss
}
